// Build the compatibility module from the same validated template used in Apps Script.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8').replace(/\r\n/g,'\n');
const base=read('apps-script/Libra.gs'), planner=read('apps-script/LibraPlanner.gs');
const core=planner.split('\nfunction libraPlannerGemini(')[0];
const helpers=base.split('\n').filter(l=>/^function libra(?:Text|Norm)\(/.test(l));
if(helpers.length!==2||!core.includes('function libraPlannerFallback(')||core===planner)throw Error('Planner template source changed unexpectedly.');
const output=`// Generated by tools/build-libra-planner-template.cjs. Edit the Apps Script source, then rebuild.\n${helpers.join('\n')}\n${core}\n\nexport function makeCompatiblePlan(payload) {\n  const options=libraPlannerOptions(payload);\n  const data={programs:libraPlannerFallback(options),method:'template',message:'Draf templat umum. Backend Planner baharu belum aktif; Gemini dan analisis data sebenar tidak digunakan.'};\n  if(options.analysis)data.analysisMessage='Analisis Dewey tidak tersedia sehingga backend Planner dikemas kini.';\n  return data;\n}\n`;
const target=path.join(root,'libra-planner-template.js');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||read('libra-planner-template.js')!==output)throw Error('Rebuild libra-planner-template.js.');
}else fs.writeFileSync(target,output,'utf8');
